import { launch, size, shot, theme, sleep, setScript, plain, three } from './p2-common.mjs'
const { app, page } = await launch()
const log = (...a) => console.log(...a)
const start = async (t) => { const ta = page.locator('.composer textarea'); await ta.fill(t); await page.locator('.composer .btn.primary').click() }
const setSidebar = async (want) => { const cur = await page.evaluate(() => document.querySelector('.sidebar').dataset.collapsed); if ((cur === 'true') !== (want === 'rail')) { await page.keyboard.press('Control+b'); await sleep(500) } }
const setSide = async (want) => { const cur = await page.evaluate(() => document.querySelector('.side-panel')?.dataset.collapsed); if (cur === undefined) return; if ((cur === 'true') !== (want === 'collapsed')) { await page.locator('.side-panel button').first().click(); await sleep(500) } }
const openProject = async (n) => { const el = page.locator(`.sidebar [data-testid=nav-project][data-name="${n}"]`); await el.click(); await sleep(400) }
await theme(page, 'dark')
await size(app, page, 1424, 881)
await setSidebar('open')
await openProject('Notes API')
await page.getByRole('tab', { name: 'Live', exact: true }).click()
// plain run then end
setScript(plain); await start('Add a /health endpoint'); await sleep(4500)
await page.getByRole('button', { name: 'End session' }).click(); await sleep(1500)
await shot(page, '16-ended-dark-1424')
log('ended composer:', await page.evaluate(() => document.querySelector('.composer').innerText))
log('strip:', await page.evaluate(() => document.querySelector('[data-testid=run-strip]').innerText))
await page.getByRole('tab', { name: 'History', exact: true }).click(); await sleep(700)
await shot(page, '17-history-dark-1424')
await page.getByRole('tab', { name: 'Org chart', exact: true }).click(); await sleep(900)
await shot(page, '18-org-dark-1424')
await size(app, page, 1024, 640); await sleep(500)
await shot(page, '18-org-dark-1024')
await size(app, page, 1424, 881)
await page.getByRole('tab', { name: 'Settings', exact: true }).click(); await sleep(700)
await shot(page, '19-psettings-dark-1424')
// App settings via gear, Appearance via UI
await page.getByRole('button', { name: 'App settings', exact: true }).click(); await sleep(700)
await shot(page, '20-appsettings-dark-1424')
log('appsettings nav:', await page.evaluate(() => document.querySelector('main, .main').innerText.slice(0, 300)))
await page.getByText('Appearance', { exact: true }).first().click().catch(() => log('no appearance link')); await sleep(500)
await page.getByRole('radio', { name: /Light/ }).check({ force: true }).catch(async () => { await page.getByText('Light', { exact: true }).first().click() }); await sleep(600)
await shot(page, '20-appearance-light-1424')
log('theme attr', await page.evaluate(() => document.documentElement.dataset.theme))
// light walks
await openProject('Notes API')
await page.getByRole('tab', { name: 'Live', exact: true }).click(); await sleep(500)
setScript(three); await page.keyboard.press('Control+t'); await sleep(400); await start('Add rate limiting to the API'); await sleep(6000)
await shot(page, '21-decisions-light-1424')
await page.getByText('Needs you · 3').click(); await sleep(400); await shot(page, '22-needs-light-1424'); await page.keyboard.press('Escape')
await page.locator('.sidebar-footer button').first().click(); await sleep(400); await shot(page, '22-account-light-1424'); await page.keyboard.press('Escape')
await size(app, page, 1600, 1000); await sleep(500)
await shot(page, '21-decisions-light-1600')
await size(app, page, 1024, 640); await sleep(500)
await setSidebar('rail'); await setSide('collapsed'); await sleep(400)
await shot(page, '21-decisions-light-1024')
await page.locator('.decision-chip').nth(0).click(); await sleep(300)
await shot(page, '21-question-light-1024')
await page.getByRole('tab', { name: 'History', exact: true }).click(); await sleep(600)
await shot(page, '23-history-light-1024')
await page.getByRole('tab', { name: 'Org chart', exact: true }).click(); await sleep(800)
await shot(page, '23-org-light-1024')
await page.locator('.sidebar [aria-label="All projects"], .sidebar .nav-item').first().click(); await sleep(600)
await shot(page, '24-projects-light-1024')
await size(app, page, 1600, 1000); await sleep(500)
await shot(page, '24-projects-light-1600')
await app.close()
