import { launch, size, shot, theme, rect, sleep, setScript, plain, three, mkRepo } from './p2-common.mjs'
setScript(plain)
const { app, page } = await launch()
async function create(name, dir) {
  const form = page.locator('form.card')
  if (!(await form.count())) await page.locator('[data-testid=new-project]').click()
  await form.waitFor()
  await form.getByRole('radio', { name: 'Existing repository', exact: true }).check({ force: true })
  await form.locator('input[placeholder*="repo"]').fill(dir)
  await form.locator('input[placeholder*="Defaults to the folder name"]').fill(name)
  const box = form.locator('[data-testid=architect-setup]')
  if (await box.isChecked()) await form.locator('label.checkbox', { hasText: 'Set up with the Architect' }).click()
  await form.getByRole('button', { name: 'Create project' }).click()
  await page.waitForSelector('form.card', { state: 'detached', timeout: 60000 })
}
await size(app, page, 1424, 881)
await create('Notes API', mkRepo('notes'))
await shot(page, '02-after-create-dark-1424')
await page.locator('.sidebar .nav-item', { hasText: 'Projects' }).first().click()
await sleep(500)
await page.locator('[data-testid=new-project]').click().catch(() => {})
await sleep(300)
await page.keyboard.press('Escape')
await shot(page, '02-projects-dark-1424')
await create('Billing Service', mkRepo('billing'))
await page.locator('.sidebar .nav-item', { hasText: 'Projects' }).first().click()
await sleep(600)
await shot(page, '02-projects-grid-dark-1424')
console.log(await page.evaluate(() => document.querySelector('main, .main')?.innerText.slice(0, 500)))
await app.close()
