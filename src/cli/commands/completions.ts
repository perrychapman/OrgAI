/**
 * `orgai completions bash|zsh|fish` (cli-spec 6.1): a static completion script generated from COMMANDS and
 * GLOBAL_FLAGS (commands, subcommands, flags and enumerated flag values). Only available commands are offered.
 * Install: `orgai completions bash > ~/.local/share/bash-completion/completions/orgai`, `orgai completions zsh >
 * "${fpath[1]}/_orgai"`, `orgai completions fish > ~/.config/fish/completions/orgai.fish`.
 */
import { COMMANDS, GLOBAL_FLAGS, type CommandEntry, type CommandFlag } from '../commandTable'
import { CliError, EXIT, type CliContext, type CommandFn } from '../types'

export const SHELLS = ['bash', 'zsh', 'fish'] as const
export type Shell = (typeof SHELLS)[number]

/**
 * Per-command flags the commands accept that commandTable.ts does not list yet (W2-T5 adds them here; a docs pass
 * should fold them into the table).
 */
const EXTRA_FLAGS: Record<string, readonly CommandFlag[]> = {
  status: [{ name: 'all-projects', takesValue: false, summary: 'Every project' }],
  runs: [
    { name: 'status', takesValue: true, values: ['running', 'needs you', 'idle', 'paused', 'finished', 'stopped', 'ended when orgai closed', 'failed'], summary: 'Only runs with this status' },
    { name: 'transcript', takesValue: false, summary: 'runs show: the whole transcript' },
    { name: 'tail', takesValue: true, summary: 'runs show: the last N transcript rows' }
  ],
  watch: [{ name: 'no-follow', takesValue: false, summary: 'Do not follow continuations' }],
  daemon: [
    { name: 'foreground', takesValue: false, summary: 'start: run the host in this terminal (inproc)' },
    { name: 'timeout', takesValue: true, summary: 'Seconds to wait' },
    { name: 'lines', short: 'n', takesValue: true, summary: 'logs: how many lines' },
    { name: 'follow', short: 'f', takesValue: false, summary: 'logs: keep printing new lines' }
  ]
}

/** The commands offered: available ones only, with their table flags plus EXTRA_FLAGS (deduped by name). */
export function completionCommands(): { entry: CommandEntry; flags: CommandFlag[] }[] {
  return COMMANDS.filter((c) => c.available).map((entry) => {
    const flags = [...entry.flags]
    for (const f of EXTRA_FLAGS[entry.name] ?? []) if (!flags.some((x) => x.name === f.name)) flags.push(f)
    return { entry, flags }
  })
}

const valueFlags = (flags: readonly CommandFlag[]): string[] => flags.filter((f) => f.takesValue).flatMap((f) => [`--${f.name}`, ...(f.short ? [`-${f.short}`] : [])])
const flagWords = (flags: readonly CommandFlag[]): string[] => flags.flatMap((f) => [`--${f.name}`, ...(f.short ? [`-${f.short}`] : [])])
/** Values with spaces cannot be offered as one shell word; keep the single-word ones. */
const wordValues = (f: CommandFlag): string[] => (f.values ?? []).filter((v) => /^[A-Za-z0-9._-]+$/.test(v))

function bashScript(): string {
  const cmds = completionCommands()
  const all = [...cmds.flatMap((c) => c.flags), ...GLOBAL_FLAGS]
  const valueCases = all
    .filter((f) => f.takesValue)
    .map((f) => {
      const pat = [`--${f.name}`, ...(f.short ? [`-${f.short}`] : [])].join('|')
      const vals = wordValues(f)
      if (f.name === 'data-dir') return `    ${pat}) COMPREPLY=($(compgen -d -- "$cur")); return ;;`
      return vals.length ? `    ${pat}) COMPREPLY=($(compgen -W "${vals.join(' ')}" -- "$cur")); return ;;` : `    ${pat}) return ;;`
    })
  const seen = new Set<string>()
  const dedupCases = valueCases.filter((l) => (seen.has(l) ? false : (seen.add(l), true)))
  const cmdCases = cmds.map(({ entry, flags }) => {
    const subs = entry.subcommands ?? []
    const words = [...flagWords(flags), ...flagWords(GLOBAL_FLAGS)].join(' ')
    if (subs.length) return `    ${entry.name}) if [[ -z "$sub" ]]; then words="${subs.join(' ')} ${words}"; else words="${words}"; fi ;;`
    return `    ${entry.name}) words="${words}" ;;`
  })
  const valueFlagList = [...new Set([...cmds.flatMap((c) => valueFlags(c.flags)), ...valueFlags(GLOBAL_FLAGS)])].join(' ')
  return `# bash completion for orgai (generated by \`orgai completions bash\`)
_orgai() {
  local cur prev cmd="" sub="" words="" i w skip=0
  cur="\${COMP_WORDS[COMP_CWORD]}"
  prev="\${COMP_WORDS[COMP_CWORD-1]}"
  local value_flags=" ${valueFlagList} "
  for ((i = 1; i < COMP_CWORD; i++)); do
    w="\${COMP_WORDS[i]}"
    if ((skip)); then skip=0; continue; fi
    if [[ "$w" == "--" ]]; then break; fi
    if [[ "$w" == -* ]]; then
      [[ "$w" != *=* && "$value_flags" == *" $w "* ]] && skip=1
      continue
    fi
    if [[ -z "$cmd" ]]; then cmd="$w"; elif [[ -z "$sub" ]]; then sub="$w"; fi
  done
  case "$prev" in
${dedupCases.join('\n')}
  esac
  if [[ -z "$cmd" ]]; then
    COMPREPLY=($(compgen -W "${cmds.map((c) => c.entry.name).join(' ')} ${flagWords(GLOBAL_FLAGS).join(' ')}" -- "$cur"))
    return
  fi
  case "$cmd" in
${cmdCases.join('\n')}
    *) words="${flagWords(GLOBAL_FLAGS).join(' ')}" ;;
  esac
  COMPREPLY=($(compgen -W "$words" -- "$cur"))
}
complete -F _orgai orgai
`
}

function zshScript(): string {
  const cmds = completionCommands()
  const all = [...cmds.flatMap((c) => c.flags), ...GLOBAL_FLAGS]
  const seen = new Set<string>()
  const valueCases = all
    .filter((f) => f.takesValue)
    .map((f) => {
      const pat = [`--${f.name}`, ...(f.short ? [`-${f.short}`] : [])].join('|')
      const vals = wordValues(f)
      if (f.name === 'data-dir') return `    ${pat}) _files -/; return ;;`
      return vals.length ? `    ${pat}) compadd -- ${vals.join(' ')}; return ;;` : `    ${pat}) return ;;`
    })
    .filter((l) => (seen.has(l) ? false : (seen.add(l), true)))
  const cmdCases = cmds.map(({ entry, flags }) => {
    const subs = entry.subcommands ?? []
    const words = [...flagWords(flags), ...flagWords(GLOBAL_FLAGS)].join(' ')
    if (subs.length) return `    ${entry.name}) if [[ -z "$sub" ]]; then compadd -- ${subs.join(' ')} ${words}; else compadd -- ${words}; fi ;;`
    return `    ${entry.name}) compadd -- ${words} ;;`
  })
  const valueFlagList = [...new Set([...cmds.flatMap((c) => valueFlags(c.flags)), ...valueFlags(GLOBAL_FLAGS)])].join(' ')
  return `#compdef orgai
# zsh completion for orgai (generated by \`orgai completions zsh\`)
_orgai() {
  local cmd="" sub="" w prev skip=0 i
  local -a value_flags
  value_flags=(${valueFlagList})
  prev="\${words[CURRENT-1]}"
  for ((i = 2; i < CURRENT; i++)); do
    w="\${words[i]}"
    if ((skip)); then skip=0; continue; fi
    [[ "$w" == "--" ]] && break
    if [[ "$w" == -* ]]; then
      [[ "$w" != *=* && \${value_flags[(Ie)$w]} -gt 0 ]] && skip=1
      continue
    fi
    if [[ -z "$cmd" ]]; then cmd="$w"; elif [[ -z "$sub" ]]; then sub="$w"; fi
  done
  case "$prev" in
${valueCases.join('\n')}
  esac
  if [[ -z "$cmd" ]]; then
    compadd -- ${cmds.map((c) => c.entry.name).join(' ')} ${flagWords(GLOBAL_FLAGS).join(' ')}
    return
  fi
  case "$cmd" in
${cmdCases.join('\n')}
    *) compadd -- ${flagWords(GLOBAL_FLAGS).join(' ')} ;;
  esac
}
_orgai "$@"
`
}

/** A fish single-quoted string. */
const fq = (s: string): string => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`

function fishFlag(f: CommandFlag, cond: string): string {
  const parts = ['complete -c orgai']
  if (cond) parts.push(`-n ${fq(cond)}`)
  parts.push(`-l ${f.name}`)
  if (f.short) parts.push(`-s ${f.short}`)
  if (f.takesValue) {
    const vals = wordValues(f)
    if (f.name === 'data-dir') parts.push('-r -F')
    else if (vals.length) parts.push(`-x -a ${fq(vals.join(' '))}`)
    else parts.push('-r')
  }
  parts.push(`-d ${fq(f.summary)}`)
  return parts.join(' ')
}

function fishScript(): string {
  const cmds = completionCommands()
  const names = cmds.map((c) => c.entry.name).join(' ')
  const lines = ['# fish completion for orgai (generated by `orgai completions fish`)', 'complete -c orgai -f']
  for (const f of GLOBAL_FLAGS) lines.push(fishFlag(f, ''))
  for (const { entry, flags } of cmds) {
    lines.push(`complete -c orgai -n ${fq(`not __fish_seen_subcommand_from ${names}`)} -a ${entry.name} -d ${fq(entry.summary)}`)
    const subs = entry.subcommands ?? []
    if (subs.length) {
      lines.push(`complete -c orgai -n ${fq(`__fish_seen_subcommand_from ${entry.name}; and not __fish_seen_subcommand_from ${subs.join(' ')}`)} -a ${fq(subs.join(' '))}`)
    }
    for (const f of flags) lines.push(fishFlag(f, `__fish_seen_subcommand_from ${entry.name}`))
  }
  return `${lines.join('\n')}\n`
}

export function completionScript(shell: Shell): string {
  return shell === 'bash' ? bashScript() : shell === 'zsh' ? zshScript() : fishScript()
}

export const runCompletions: CommandFn = async (ctx: CliContext, args: string[]): Promise<number> => {
  const shell = args[0]
  if (args.length !== 1 || !(SHELLS as readonly string[]).includes(shell)) {
    throw new CliError(`Use: orgai completions ${SHELLS.join(' | ')}${shell && args.length === 1 ? ` (unknown shell "${shell.slice(0, 32)}")` : ''}`, EXIT.usage)
  }
  ctx.io.stdout.write(completionScript(shell as Shell))
  return EXIT.ok
}
