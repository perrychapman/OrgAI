const pairKey = (a: string, b: string): string => (a <= b ? `${a}|${b}` : `${b}|${a}`)
const allEdgePairs = new Set(G.edges.map((e) => pairKey(e.from, e.to)))
const ratio = (tp: number, n: number): number => (n === 0 ? 0 : Math.round((tp / n) * 1000) / 1000)

