function* pairsOf(ids: string[]): Generator<[string, string]> {
  for (let i = 0; i < ids.length; i++) for (let j = i + 1; j < ids.length; j++) yield [ids[i], ids[j]]
}

/** REJECTED candidate: entities linking one context note. Returns pairs with no recorded edge. */
function sharedNotePairs(graphIn: KnowledgeGraph, hub: number): { a: string; b: string; useful: boolean }[] {
  const byNote = new Map<string, string[]>()
  for (const n of graphIn.nodes) if (!n.retired) for (const id of new Set(n.noteIds ?? [])) (byNote.get(id) ?? byNote.set(id, []).get(id)!).push(n.id)
  const seen = new Map<string, { a: string; b: string; useful: boolean }>()
  for (const [noteId, ids] of byNote) {
    if (ids.length < 2 || ids.length > hub) continue
    for (const [a, b] of pairsOf(ids)) {
      const k = pairKey(a, b)
      const useful = !T.incidentalNotes.has(`${noteId}>${a}`) && !T.incidentalNotes.has(`${noteId}>${b}`)
      const hit = seen.get(k)
      if (hit) hit.useful = hit.useful || useful
      else seen.set(k, { a, b, useful })
    }
  }
  return [...seen.values()].filter((p) => !allEdgePairs.has(pairKey(p.a, p.b)))
}

/** REJECTED candidate: entities with the same relation to one target. */
function sameTargetPairs(graphIn: KnowledgeGraph, hub: number): { a: string; b: string; useful: boolean }[] {
  const groups = new Map<string, { key: string; from: Set<string> }>()
  for (const e of graphIn.edges) {
    if (e.retired || !live.has(e.from) || !live.has(e.to) || e.from === e.to) continue
    const k = `${e.relation}\u0000${e.to}`
    const g = groups.get(k) ?? groups.set(k, { key: `${e.relation}>${nameOf.get(e.to)}`, from: new Set() }).get(k)!
    g.from.add(e.from)
  }
  const seen = new Map<string, { a: string; b: string; useful: boolean }>()
  for (const g of groups.values()) {
    if (g.from.size < 2 || g.from.size > hub) continue
    for (const [a, b] of pairsOf([...g.from])) {
      const k = pairKey(a, b)
      const useful = SAME_TARGET_USEFUL.has(g.key)
      const hit = seen.get(k)
      if (hit) hit.useful = hit.useful || useful
      else seen.set(k, { a, b, useful })
    }
  }
  return [...seen.values()].filter((p) => !allEdgePairs.has(pairKey(p.a, p.b)))
}

/** REJECTED candidate: entities written by the same run. Related = a recorded edge or an intended mention either way. */
function sameRunPairs(): { pairs: number; related: number; unlinked: number; unlinkedRelated: number } {
  const byRun = new Map<string, string[]>()
  for (const n of G.nodes) if (!n.retired && n.source.by === 'agent' && n.source.runId) (byRun.get(n.source.runId) ?? byRun.set(n.source.runId, []).get(n.source.runId)!).push(n.id)
  let pairs = 0
  let related = 0
  let unlinked = 0
  let unlinkedRelated = 0
  for (const ids of byRun.values()) {
    for (const [a, b] of pairsOf(ids)) {
      pairs++
      const edged = allEdgePairs.has(pairKey(a, b))
      const rel = edged || T.mentions.has(`${a}>${b}`) || T.mentions.has(`${b}>${a}`)
      if (rel) related++
      if (!edged) {
        unlinked++
        if (rel) unlinkedRelated++
      }
    }
  }
  return { pairs, related, unlinked, unlinkedRelated }
}

