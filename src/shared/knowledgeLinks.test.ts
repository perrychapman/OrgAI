/** For every intended mention found by the matcher: does a recorded edge in the same direction carry the table's word? */
function kindPairAccuracy(table: Record<string, string>): Record<string, { mentions: number; labelled: number; correct: number; reversed: number }> {
  const out: Record<string, { mentions: number; labelled: number; correct: number; reversed: number }> = {}
  for (const l of knowledgeMentions(G)) {
    if (!T.mentions.has(`${l.from}>${l.to}`)) continue
    const key = `${byId.get(l.from)!.kind}>${byId.get(l.to)!.kind}`
    if (!(key in table)) continue
    const row = (out[key] ??= { mentions: 0, labelled: 0, correct: 0, reversed: 0 })
    row.mentions++
    const fwd = G.edges.filter((e) => !e.retired && e.from === l.from && e.to === l.to)
    const back = G.edges.filter((e) => !e.retired && e.from === l.to && e.to === l.from)
    if (fwd.length > 0) {
      row.labelled++
      if (fwd.some((e) => e.relation === table[key])) row.correct++
    } else if (back.length > 0) row.reversed++
  }
  return out
}

function evaluate(): Record<string, unknown> {
  const m: Record<string, unknown> = {}
  const sets: Record<string, { caseSensitiveSingles?: boolean; commonWordGuard?: boolean } | undefined> = {
    shipped: undefined,
    noCaseRule: { caseSensitiveSingles: false },
    noCommonWordGuard: { commonWordGuard: false },
    naive: { caseSensitiveSingles: false, commonWordGuard: false }
  }
  for (const [name, rules] of Object.entries(sets)) {
    const ls = knowledgeMentions(G, rules)
    const tp = ls.filter((l) => T.mentions.has(`${l.from}>${l.to}`)).length
    m[`mention.${name}`] = { links: ls.length, correct: tp, precision: ratio(tp, ls.length), recall: ratio(tp, liveTruth.length) }
  }
  m['mention.truth'] = liveTruth.length
  const shipped = knowledgeMentions(G)
  for (const t of [0.5, 0.65]) {
    const s = shipped.filter((l) => l.strength >= t)
    m[`mention.strength>=${t}`] = { links: s.length, correct: s.filter((l) => T.mentions.has(`${l.from}>${l.to}`)).length }
  }
  // what a user or agent would see: pairs without a recorded edge
  for (const hub of [undefined, 12, 8, 4]) {
    const ls = inferKnowledgeLinks(G, { hubCutoff: hub }).filter((l) => l.basis === 'mention')
    m[`mention.suggested.hub=${hub ?? 'none'}`] = { links: ls.length, correct: ls.filter((l) => T.mentions.has(`${l.from}>${l.to}`)).length }
  }
  const strong = strongMentionLinks(inferKnowledgeLinks(G))
  m['mention.strongSuggested'] = { links: strong.length, correct: strong.filter((l) => T.mentions.has(`${l.from}>${l.to}`)).length }
  const sameName = inferKnowledgeLinks(G).filter((l) => l.basis === 'same-name')
  m['same-name'] = { links: sameName.length, useful: sameName.filter((l) => SAME_NAME_USEFUL.has(nameOf.get(l.from)!)).length }
  for (const hub of [4, 6, 8, 12, 40]) {
    const sn = sharedNotePairs(G, hub)
    m[`shared-note.hub=${hub}`] = { pairs: sn.length, useful: sn.filter((p) => p.useful).length }
    const st = sameTargetPairs(G, hub)
    m[`same-target.hub=${hub}`] = { pairs: st.length, useful: st.filter((p) => p.useful).length }
  }
  m['same-run'] = sameRunPairs()
  m['kind-pair.candidates'] = kindPairAccuracy(CANDIDATE_KIND_PAIRS)
  m['kind-pair.shipped'] = kindPairAccuracy(KNOWLEDGE_KIND_PAIR_RELATIONS as Record<string, string>)
  // Does one recall (default budget, the question as the query) surface what a good answer needs, versus the keyword search of today?
  const inList = (names: string[], want: string[]): number => want.filter((w) => names.includes(w)).length
  const questions = KNOWLEDGE_FIXTURE_QUESTIONS.map((q) => {
    const recall = recallKnowledge(G, q.question)
    const keyword = searchKnowledge(G, { query: q.keyword }).map((h) => h.node.name)
    // recall counts a name that appears anywhere in its text (as an entity or as a neighbour); the keyword search only lists entities
    return { wanted: q.expectedNames.length, recall: q.expectedNames.filter((w) => recall.text.includes(w)).length, recallChars: recall.text.length, keywordHits: keyword.length, keyword: inList(keyword, q.expectedNames) }
  })
  m['questions'] = questions
  return m
}

